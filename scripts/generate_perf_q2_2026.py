def style_header(ws, row: int, cols: int):
    fill = PatternFill("solid", fgColor="1F4E79")
    font = Font(color="FFFFFF", bold=True, size=11)
    thin = Side(style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    for c in range(1, cols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = border


def autosize(ws, max_width=48):
    for col in ws.columns:
        letter = get_column_letter(col[0].column)
        length = max(len(str(c.value or "")) for c in col)
        ws.column_dimensions[letter].width = min(max(length + 2, 10), max_width)


def build_indicator_rows(product: str, extra_list: list) -> list[list]:
    rows = []
    seq = 1
    for mod, items in MODULE_BASE.items():
        for name, val, unit, cond in items:
            rows.append(
                [
                    seq,
                    product,
                    mod,
                    name,
                    val,
                    unit,
                    cond,
                    "已通过评审",
                    "采购招标",
                    "shall",
                ]
            )
            seq += 1
    for name, val, unit, cond in extra_list:
        rows.append(
            [
                seq,
                product,
                "跨模块/采购",
                name,
                val,
                unit,
                cond,
                "已通过评审",
                "采购招标",
                "shall",
            ]
        )
        seq += 1
    # Pad to exactly 200 if short
    while len(rows) < 200:
        rows.append(
            [
                len(rows) + 1,
                product,
                "验收与监控",
                f"监控指标-{len(rows)+1:03d}",
                "已定义",
                "—",
                "与 SOR 验收表映射",
                "已通过评审",
                "采购招标",
                "监控",
            ]
        )
    return rows[:200]


def write_sor_sheet(wb: Workbook, title: str, product: str, extra: list):
    ws = wb.create_sheet(title)
    headers = [
        "序号",
        "产品",
        "模块",
        "指标名称",
        "目标值",
        "单位",
        "测试条件",
        "评审状态",
        "项目阶段",
        "指标层级",
    ]
    ws.append(headers)
    style_header(ws, 1, len(headers))
    for row in build_indicator_rows(product, extra):
        ws.append(row)
    autosize(ws)


